/**
 * Chooses the opening level's hook seed (ADR-0003). Of the defaults sweep's seeds on which
 * the chosen defaults succeed, it picks the one whose flock becomes a single group soonest
 * and stays one to the end of the window. This is not a new sweep: it re-runs the chosen
 * defaults on the sweep's own seeds, measuring every step instead of once a second.
 * Pure and deterministic.
 */
import { flockPlanarWeighted as flock, flockReadsAsOneGroup, type FlockParams } from "@paperplay/primitives";
import { judge } from "./flock-sweep.ts";

/** One seed's flock, measured at step 0 and after every step up to `steps`. */
export interface SeedRun {
  readonly seed: number;
  readonly steps: number;
  readonly clusterCount: readonly number[];
  readonly strayShare: readonly number[];
  readonly agreement: readonly number[];
}

export interface SeedSummary {
  readonly seed: number;
  /** The sweep's criterion at the last step: agreement ≥ 0.8 as one group. */
  readonly qualified: boolean;
  readonly finalAgreement: number;
  readonly finalGroups: number;
  /** The first step with a single group, even if it split again later. */
  readonly firstSingleGroup: number | null;
  /** The first step from which the flock stays one group to the end. */
  readonly singleGroupFrom: number | null;
  /** The first step from which the sweep's criterion holds to the end. */
  readonly orderedFrom: number | null;
}

export function runSeed(params: FlockParams, seed: number, steps: number): SeedRun {
  let state = flock.init(params, seed);
  const clusterCount: number[] = [];
  const strayShare: number[] = [];
  const agreement: number[] = [];
  for (let t = 0; t <= steps; t++) {
    if (t > 0) state = flock.step(state, params, flock.fixedTimestep);
    const observed = flock.measure(state);
    clusterCount.push(observed.clusterCount);
    strayShare.push(observed.strayShare);
    agreement.push(observed.directionalAgreement);
  }
  return { seed, steps, clusterCount, strayShare, agreement };
}

/** The first index from which every value is true; null when the last one is false (or there are none). */
export function holdsFrom(holds: readonly boolean[]): number | null {
  let from: number | null = null;
  for (let index = holds.length - 1; index >= 0 && holds[index] === true; index--) from = index;
  return from;
}

export function summarise(run: SeedRun): SeedSummary {
  // One group means O1 (ADR-0015): exactly one group, holding at least half the birds.
  const single = run.clusterCount.map((groups, index) => flockReadsAsOneGroup({ clusterCount: groups, strayShare: run.strayShare[index] ?? 1 }));
  const ordered = single.map((one, index) => one && judge(run.agreement[index] ?? Number.NaN, 1));
  const first = single.indexOf(true);
  return {
    seed: run.seed,
    qualified: ordered.at(-1) === true,
    finalAgreement: run.agreement.at(-1) ?? Number.NaN,
    finalGroups: run.clusterCount.at(-1) ?? Number.NaN,
    firstSingleGroup: first === -1 ? null : first,
    singleGroupFrom: holdsFrom(single),
    orderedFrom: holdsFrom(ordered),
  };
}

/** The qualified seed that forms one group soonest for good, then orders soonest, then the lower seed. */
export function chooseHookSeed(summaries: readonly SeedSummary[]): SeedSummary | undefined {
  const late = (step: number | null) => step ?? Number.POSITIVE_INFINITY;
  return summaries
    .filter((s) => s.qualified)
    .toSorted((a, b) => late(a.singleGroupFrom) - late(b.singleGroupFrom) || late(a.orderedFrom) - late(b.orderedFrom) || a.seed - b.seed)
    .at(0);
}

const seconds = (step: number | null) => (step === null ? "never" : (step * flock.fixedTimestep).toFixed(2));

/** The record in eval/sweeps/hook-seed.md: every seed, the rule, and the choice. */
export function toMarkdown(
  summaries: readonly SeedSummary[],
  chosen: SeedSummary | undefined,
  meta: { readonly primitive: string; readonly runtime: string },
): string {
  const rows = summaries.map(
    (s) =>
      `| ${s.seed} | ${s.qualified ? "yes" : "no"} | ${s.finalAgreement.toFixed(4)} | ${s.finalGroups} | ${seconds(s.firstSingleGroup)} | ${seconds(s.singleGroupFrom)} | ${seconds(s.orderedFrom)} |`,
  );
  const qualified = summaries.filter((s) => s.qualified).length;
  const choice = chosen
    ? `Hook seed: **${chosen.seed}**. Its flock is one group from ${seconds(chosen.singleGroupFrom)} s and ordered from ${seconds(chosen.orderedFrom)} s.`
    : "No seed qualified, so no hook seed was chosen.";
  return `# Hook seed

Generated by \`npm run choose:hook-seed\` (scripts/hook-seed.ts) on ${meta.runtime} with
${meta.primitive} at its defaults. Deterministic: rerunning it on the same commit rewrites
this file byte for byte. ADR-0003 records the decision this informs.

## Rule

The owner's rule (2026-10-01): from the sweep seeds that qualified, pick the one that forms
a single group fastest. It is shown on the opening level as a teaching choice, while free
exploration keeps other seeds.

- **Qualified:** the defaults sweep's criterion at 20 s (step 1200), meaning directional
  agreement ≥ 0.8 as a single group (\`eval/sweeps/flock-defaults.md\`).
- **Forms a single group:** the first step from which the flock reads as one group (O1,
  ADR-0015) to 20 s: exactly one group, holding at least half the birds. A flock that is
  briefly one group and then splits has not formed one.
- **Ties:** go to the seed that stays ordered sooner, then to the lower seed.

This re-runs the chosen defaults on the sweep's own seeds 1–${summaries.length}, measuring after every step rather
than once a second. It varies no parameter, so it is not a new sweep.

## Result

${choice} ${qualified} of ${summaries.length} seeds qualified.

| Seed | Qualified | Agreement at 20 s | Groups at 20 s | First one group (s) | One group from (s) | Ordered from (s) |
|---|---|---|---|---|---|---|
${rows.join("\n")}
`;
}
