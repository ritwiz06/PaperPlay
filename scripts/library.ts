/**
 * npm run library
 *
 * Writes apps/web/src/library/worlds.json, the library page's index (ADR-0049): every world the
 * build holds, hand-made and generated, with its paper, its kind, its status, its levels and its
 * thumbnail, read from the fixtures. A generated world also says when its job was recorded, and which
 * of its levels today's definitional rule finds definitional (ADR-0044). With --print, prints it
 * instead, for the test that holds the index to the fixtures.
 */
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { FAMILIES, WorldSpecV3 } from "@paperplay/contracts";

type WorldSpec = ReturnType<typeof WorldSpecV3.parse>;
const WorldSpec = WorldSpecV3;
import { directEffectOf } from "@paperplay/pipeline";

const root = join(import.meta.dirname, "..");
const FIXTURES = join(root, "fixtures", "worldspecs");

/** The hand-made worlds and the routes the shell plays them on. */
export const HAND_MADE = [
  { file: "flocking-reference.json", id: "murmuration-valley", route: "/world/hook" },
  { file: "kermack-mckendrick-1927.json", id: "threshold-town", route: "/world/epidemic" },
  { file: "sutskever-2013-momentum.json", id: "momentum-valley", route: "/world/momentum" },
] as const;

export interface LibraryWorld {
  readonly id: string;
  /** Where the shell plays it, or null for a retired world, which it no longer plays. */
  readonly route: string | null;
  readonly title: string;
  /** Who made it: by hand, or by the pipeline from the paper. */
  readonly madeBy: "hand" | "pipeline";
  /** Verified: hand-made and reviewed against its source map; a draft; generated by the pipeline; or retired. */
  readonly status: "verified" | "draft" | "generated" | "retired";
  /** The family its primitive belongs to, in words. */
  readonly family: string;
  readonly paper: { readonly title: string; readonly authors: readonly string[]; readonly year: number; readonly venue: string | null };
  readonly levels: readonly { readonly order: number; readonly title: string; readonly bonus: boolean }[];
  readonly thumbnail: string;
  /** For a generated world: the day its job was recorded. */
  readonly recordedOn: string | null;
  /** For a generated world: its levels today's definitional rule finds definitional, by order. */
  readonly definitional: readonly number[];
  /** For a retired world: when, why, and the world that replaces it. */
  readonly retired: { readonly on: string; readonly reason: string; readonly replacedBy: string | null } | null;
}

interface Retired {
  readonly retiredOn: string;
  readonly reason: string;
  readonly replacedBy: string | null;
}
const RETIRED = join(FIXTURES, "retired");
const retiredOnes = (): Readonly<Record<string, Retired>> => (JSON.parse(readFileSync(join(RETIRED, "retired.json"), "utf8")) as { worlds: Record<string, Retired> }).worlds;

/** Which recorded job made each generated world, by the world's path. */
function recordedOn(): ReadonlyMap<string, string> {
  const folder = join(root, "fixtures", "jobs");
  const found = new Map<string, string>();
  for (const file of readdirSync(folder).filter((name) => name.endsWith(".json"))) {
    const record = JSON.parse(readFileSync(join(folder, file), "utf8")) as { world?: string; recordedOn?: string };
    if (record.world && record.recordedOn) found.set(record.world, record.recordedOn);
  }
  return found;
}

/** The levels a world's own models make definitional (ADR-0044, judged by compartment since 2026-10-20). */
function definitionalLevels(spec: WorldSpec): number[] {
  return spec.levels.flatMap((level) => {
    if (level.binding.type !== "equations") return [];
    const model = level.binding.model;
    const difference = level.counterfactual.difference;
    if (!("summary" in difference) || !("time" in difference)) return [];
    const summary = difference.summary;
    const at = summary.kind === "at" ? summary.time : summary.kind === "first-reach" ? summary.threshold : summary.kind === "lowest" ? summary.from : null;
    const metric = model.observables.find((observable) => observable.id === difference.metricId);
    const compartment = metric && "c" in metric.expr ? metric.expr.c : null;
    if (!compartment) return [];
    return directEffectOf(model, level.manipulable.targetVariable, compartment, { summary: summary.kind, at, time: difference.time }).definitional ? [level.order] : [];
  });
}

function entryOf(spec: WorldSpec, id: string, route: string | null, madeBy: LibraryWorld["madeBy"], recorded: string | null, retired: Retired | null = null): LibraryWorld {
  const source = spec.source;
  const family = FAMILIES[spec.routing.family];
  return {
    id,
    route,
    title: spec.title,
    madeBy,
    status: retired ? "retired" : madeBy === "pipeline" ? "generated" : spec.status === "reviewed" ? "verified" : "draft",
    family: family.name,
    paper: { title: source.title, authors: source.authors, year: source.year, venue: source.venue ?? null },
    levels: spec.levels.map((level) => ({ order: level.order, title: level.title, bonus: level.bonus })),
    thumbnail: `/library/${id}.jpg`,
    recordedOn: recorded,
    definitional: madeBy === "pipeline" && !retired ? definitionalLevels(spec) : [],
    retired: retired ? { on: retired.retiredOn, reason: retired.reason, replacedBy: retired.replacedBy } : null,
  };
}

/** Every world, hand-made first, then the generated ones by paper and newest first, the retired ones last. */
export function libraryWorlds(): LibraryWorld[] {
  const recorded = recordedOn();
  const handMade = HAND_MADE.map(({ file, id, route }) => entryOf(WorldSpec.parse(JSON.parse(readFileSync(join(FIXTURES, file), "utf8"))), id, route, "hand", null));
  const generated = readdirSync(join(FIXTURES, "generated"))
    .filter((name) => name.endsWith(".json"))
    .map((name) => {
      const id = name.replace(/\.json$/, "");
      const path = `fixtures/worldspecs/generated/${name}`;
      return entryOf(WorldSpec.parse(JSON.parse(readFileSync(join(root, path), "utf8"))), id, `/world/generated/${id}`, "pipeline", recorded.get(path) ?? null);
    })
    .sort((a, b) => a.paper.title.localeCompare(b.paper.title) || (b.recordedOn ?? "").localeCompare(a.recordedOn ?? "") || b.id.localeCompare(a.id));
  const why = retiredOnes();
  const retired = Object.keys(why)
    .sort()
    .reverse()
    .map((id) => {
      const path = `fixtures/worldspecs/retired/${id}.json`;
      return entryOf(WorldSpec.parse(JSON.parse(readFileSync(join(root, path), "utf8"))), id, null, "pipeline", recorded.get(path) ?? null, why[id] ?? null);
    });
  return [...handMade, ...generated, ...retired];
}

export const libraryJson = (): string => `${JSON.stringify({ schemaVersion: "library/1", worlds: libraryWorlds() }, null, 2)}\n`;

if (import.meta.main) {
  if (process.argv.includes("--print")) process.stdout.write(libraryJson());
  else {
    const out = join(root, "apps", "web", "src", "library", "worlds.json");
    if (!existsSync(join(root, "apps", "web", "src", "library"))) throw new Error("apps/web/src/library/ is missing");
    writeFileSync(out, libraryJson());
    console.log(`wrote ${out}`);
  }
}
